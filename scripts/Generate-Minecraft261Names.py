"""Generate compile-time Mojang spellings for the staged 26.1 native SDK.

Consumes the local 1.21.11 official development mappings only; never downloads
or enables a DLL target. A spelling is not proof of a 26.1 signature or behavior.
"""
import argparse
from collections import defaultdict
from pathlib import Path
import re

from minecraft_classfile import read_intermediary, read_proguard, remap_descriptor

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/sdk/minecraft/fabric_26_1/official_names.hpp"
VERSIONS = ("1.21.11",)
LITERAL = re.compile(r'"([^"\n]*(?:net[/.]minecraft[/.]class_\d+|(?:method|field|comp)_\d+)[^"\n]*)"')
# These unverified historical fallback/unused draw names are never compiled for 26.1.
LEGACY_ONLY = {"method_19349", "method_30881"}
# Verified against the official 26.1 classfiles, not inferred from spelling.
OVERRIDES = {
    "net/minecraft/class_1713": "net/minecraft/world/inventory/ContainerInput",
    "net/minecraft/class_777": "net/minecraft/client/resources/model/geometry/BakedQuad",
    "net/minecraft/class_804": "net/minecraft/client/resources/model/cuboid/ItemTransform",
    "method_2906": "handleContainerInput",
    "method_2883": "send",
    "field_56967": "itemTransform",
}


def source_tokens():
    result = set()
    for path in (ROOT / "src").rglob("*"):
        if path.suffix not in (".hpp", ".cpp") or path == OUTPUT:
            continue
        result.update(LITERAL.findall(path.read_text(encoding="utf-8")))
    return result - LEGACY_ONLY


def mapping_table(cache):
    classes, members = {}, {}
    wanted = source_tokens()
    for version in VERSIONS:
        intermediary, records = read_intermediary(cache / f"intermediary-{version}.jar")
        mojang, named = read_proguard((cache / f"client-{version}.txt").read_text(encoding="utf-8"))
        for obfuscated, inter in intermediary.items():
            if obfuscated in mojang: classes.setdefault(inter, mojang[obfuscated])
        candidates = defaultdict(set)
        for (_, inter, _), declarations in records.items():
            for owner, obfuscated, descriptor in declarations:
                if value := named.get((owner, "method" if descriptor.startswith("(") else "field", obfuscated, descriptor)):
                    candidates[inter].add(value[1])
        for inter, spellings in candidates.items():
            if inter in members or inter not in wanted: continue
            if len(spellings) != 1:
                raise ValueError(f"Ambiguous Mojang spelling for {inter}: {sorted(spellings)}")
            members[inter] = spellings.pop()
    return classes, members


def translate(token, classes, members):
    if token in OVERRIDES: return OVERRIDES[token]
    if token in members: return members[token]
    if token in classes: return classes[token]
    if token.replace(".", "/") in classes:
        return classes[token.replace(".", "/")].replace("/", ".")
    if token.startswith(("(", "L", "[")):
        result = remap_descriptor(token, {**classes, **{k: v for k, v in OVERRIDES.items() if k.startswith("net/")}})
        if "net/minecraft/class_" not in result: return result
    raise ValueError(f"No verified historical spelling for {token}")


def render(tokens, classes, members):
    rows = []
    for token in sorted(tokens):
        target = translate(token, classes, members)
        if not re.fullmatch(r"[\w/.$;()\[<>]+", token + target):
            raise ValueError("Unexpected generated C++ symbol characters")
        rows.append(f'template<> struct symbol<"{token}"> {{ static constexpr auto value = jni::string_litteral("{target}"); }};')
    return "\n".join([
        "#pragma once", "// Generated by scripts/Generate-Minecraft261Names.py; do not edit spellings by hand.",
        "// Historical spellings only. Version-specific API changes require explicit SDK adaptations.",
        '#include "../../../meta_jni.hpp"', "namespace mc261::names", "{",
        "template<jni::string_litteral Source> struct symbol;", *rows, "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache-dir", type=Path, required=True)
    parser.add_argument("--write", action="store_true", help="Regenerate only the compile-time spelling header")
    args = parser.parse_args()
    try:
        classes, members = mapping_table(args.cache_dir)
        result = render(source_tokens(), classes, members)
        if args.write:
            OUTPUT.parent.mkdir(parents=True, exist_ok=True)
            OUTPUT.write_text(result, encoding="utf-8")
        elif not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != result:
            parser.exit(1, "Generated 26.1 names are stale; run with --write\n")
        print(f"PASS: {len(source_tokens())} explicit compile-time 26.1 spellings")
    except (OSError, ValueError) as error:
        parser.exit(2, f"Generation failed: {error}\n")


if __name__ == "__main__":
    main()
